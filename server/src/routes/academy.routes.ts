import { Router } from 'express';
import { catalog, courseDetail, learn, classSchedule, joinMeet, recording, instructorProfile, myEnrollments, enrollCourse } from '../controllers/academy.controller.js';
import { authenticate, optionalAuthenticate } from '../middleware/auth.js';
import { noStore } from '../middleware/noStore.js';
import { requireActiveEnrollment } from '../middleware/requireActiveEnrollment.js';
const router = Router();
router.get('/courses', optionalAuthenticate, catalog);
router.get('/courses/:id', optionalAuthenticate, courseDetail);
router.get('/my-enrollments', authenticate, noStore, myEnrollments);
router.post('/enroll', authenticate, noStore, enrollCourse);
router.get('/courses/:courseId/lessons/:lessonId', authenticate, noStore, requireActiveEnrollment, learn);
router.get('/classes', optionalAuthenticate, classSchedule);
router.get('/courses/:courseId/classes', optionalAuthenticate, classSchedule);
router.get('/classes/:classId/join', authenticate, noStore, requireActiveEnrollment, joinMeet);
router.get('/classes/:classId/recording', authenticate, noStore, requireActiveEnrollment, recording);
router.get('/instructors/:id', instructorProfile);
export default router;
