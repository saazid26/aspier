import { Router } from 'express';
import { z } from 'zod';
import { authenticate, authorize } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import { noStore } from '../middleware/noStore.js';
import { paymentLimiter } from '../middleware/rateLimit.js';
import { submitPayment, paymentStatus, paymentHistory, paymentQueue, approvePayment, rejectPayment, deletePayment } from '../controllers/payment.controller.js';
const router = Router();
router.post('/', authenticate, noStore, paymentLimiter, validate(z.object({ courseId: z.string().min(1), method: z.enum(['bKash', 'Nagad']), senderNumber: z.string().min(11), trxId: z.string().min(3).max(80), amount: z.number().positive() })), submitPayment);
router.get('/status/:courseId', authenticate, noStore, paymentStatus);
router.get('/history', authenticate, noStore, paymentHistory);
router.get('/queue', authenticate, authorize('admin', 'superadmin'), noStore, paymentQueue);
router.post('/:id/approve', authenticate, authorize('admin', 'superadmin'), noStore, approvePayment);
router.post('/:id/reject', authenticate, authorize('admin', 'superadmin'), noStore, validate(z.object({ reason: z.string().min(2).max(1000) })), rejectPayment);
router.delete('/:id', authenticate, authorize('admin', 'superadmin'), noStore, deletePayment);
export default router;
